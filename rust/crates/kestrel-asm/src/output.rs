// The three files the build can ask for besides the image: a C++ header of the
// bytes, a symbol table, and a listing.
//
// All three are textual and their layout is what the C++ tool produced, so the
// build's generated headers and the repository's own copies of them stay
// identical.

use crate::assembler::ListingEntry;
use crate::expr::SymbolTable;

pub fn header_text(name: &str, origin: u32, image: &[u8]) -> String {
    let upper = name.to_ascii_uppercase();
    let mut out = String::new();
    out.push_str("// SPDX-License-Identifier: MIT\n");
    out.push_str("//\n");
    out.push_str(&format!(
        "// Generated by kestrel_asm from roms/kestrel/{name}.s -- do not edit.\n"
    ));
    out.push_str("//\n");
    out.push_str(&format!(
        "// The {name} ROM: {} bytes of 6502 machine code,\n",
        image.len()
    ));
    out.push_str(&format!(
        "// assembled at ${origin:X}. This is what the machine boots.\n\n"
    ));
    out.push_str("#pragma once\n\n");
    out.push_str("#include <array>\n");
    out.push_str("#include <cstdint>\n\n");
    out.push_str("namespace kestrel::model1982::rom {\n\n");
    out.push_str(&format!(
        "inline constexpr std::uint16_t k{upper}Origin = 0x{origin:X};\n"
    ));
    out.push_str(&format!(
        "inline constexpr std::array<std::uint8_t, {}> k{upper}Image = {{",
        image.len()
    ));
    for (index, byte) in image.iter().enumerate() {
        if index % 16 == 0 {
            out.push_str("\n    ");
        }
        out.push_str(&format!("0x{byte:02X},"));
    }
    out.push_str("\n};\n\n");
    out.push_str("}  // namespace kestrel::model1982::rom\n");
    out
}

/// One symbol per line, ordered by value and then by name, which is the order a
/// reader wants when working out where in the image something lives.
pub fn symbol_text(symbols: &SymbolTable) -> String {
    let mut ordered: Vec<(i64, &String)> =
        symbols.iter().map(|(name, value)| (*value, name)).collect();
    ordered.sort();
    let mut out = String::new();
    for (value, name) in ordered {
        out.push_str(&format!("{:04X} {name}\n", (value & 0xFFFF) as u64));
    }
    out
}

/// The bytes of each statement beside the line that produced them.
pub fn listing_text(listing: &[ListingEntry], image: &[u8], base: u32) -> Vec<u8> {
    let mut out = Vec::new();
    for entry in listing {
        out.extend_from_slice(format!("{:04X}  ", entry.address).as_bytes());
        let mut bytes = String::new();
        for address in entry.address..entry.end {
            let index = address.wrapping_sub(base);
            if index as usize >= image.len() {
                break;
            }
            bytes.push_str(&format!("{:02X} ", image[index as usize]));
        }
        while bytes.len() < 12 {
            bytes.push(' ');
        }
        out.extend_from_slice(bytes.as_bytes());
        out.extend_from_slice(b"  ");
        out.extend_from_slice(&entry.text);
        out.push(b'\n');
    }
    out
}
