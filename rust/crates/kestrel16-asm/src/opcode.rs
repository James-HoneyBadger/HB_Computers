pub fn find_opcode(name: &str, mode: Mode) -> Option<&'static OpDef> {
    OPCODES.iter().find(|op| op.name == name && op.mode == mode)
}

pub fn op_supports(name: &str, mode: Mode) -> bool {
    find_opcode(name, mode).is_some()
}

pub fn is_mnemonic(name: &str) -> bool {
    OPCODES.iter().any(|op| op.name == name)
}

/// The part of a mnemonic before a `.B`, `.W` or `.L` suffix. The suffix only
/// chooses a width, so every test for "is this a mnemonic" has to look at the
/// name without it -- otherwise `LDA.B` at the start of a line would be read as
/// a label called `LDA.B`.
pub fn base_mnemonic(name: &str) -> &str {
    match name.rsplit_once('.') {
        Some((head, "B" | "W" | "L")) => head,
        _ => name,
    }
}
