// The instruction set: every documented 65C816 opcode, with the addressing mode
// each one takes. Undocumented opcodes are not assembled: a ROM that needs one
// emits `.byte` and says why in a comment.
//
// A mnemonic appears once per mode it supports, which is what makes mode
// selection a lookup rather than a table of bit patterns: `LDA ($10),Y` is the
// direct-page indirect form, `JML [$1234]` the absolute indirect long one, and
// the table is where the difference between them is written down.
//
// The width suffixes are part of the mnemonic as the source writes it -- `LDA.B`,
// `LDA.W`, `LDA.L` -- but they name the same instruction, so the table holds the
// bare name and `base_mnemonic` strips the suffix before the lookup.

use std::fmt;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Mode {
    Imp,
    Imp8,
    Acc,
    Imm,
    Imm8,
    Imm16,
    Dp,
    DpX,
    DpY,
    DpInd,
    DpIndX,
    DpIndY,
    DpLong,
    DpLongY,
    SrS,
    SrSY,
    Abs,
    AbsX,
    AbsY,
    AbsInd,
    AbsIndX,
    AbsIndLong,
    Long,
    LongX,
    Rel,
    Rel16,
    Blk,
}

impl Mode {
    /// The mode as a diagnostic names it, so an unsupported form says which one
    /// it was.
    pub fn name(self) -> &'static str {
        match self {
            Mode::Imp => "implied",
            Mode::Imp8 => "implied, signature",
            Mode::Acc => "accumulator",
            Mode::Imm => "immediate",
            Mode::Imm8 => "immediate byte",
            Mode::Imm16 => "immediate word",
            Mode::Dp => "direct page",
            Mode::DpX => "direct page,X",
            Mode::DpY => "direct page,Y",
            Mode::DpInd => "(direct page)",
            Mode::DpIndX => "(direct page,X)",
            Mode::DpIndY => "(direct page),Y",
            Mode::DpLong => "[direct page]",
            Mode::DpLongY => "[direct page],Y",
            Mode::SrS => "stack relative",
            Mode::SrSY => "(stack relative),Y",
            Mode::Abs => "absolute",
            Mode::AbsX => "absolute,X",
            Mode::AbsY => "absolute,Y",
            Mode::AbsInd => "(absolute)",
            Mode::AbsIndX => "(absolute,X)",
            Mode::AbsIndLong => "[absolute]",
            Mode::Long => "long",
            Mode::LongX => "long,X",
            Mode::Rel => "relative",
            Mode::Rel16 => "relative long",
            Mode::Blk => "block move",
        }
    }
}

impl fmt::Display for Mode {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.name())
    }
}

pub struct OpDef {
    pub name: &'static str,
    pub mode: Mode,
    pub code: u8,
}

